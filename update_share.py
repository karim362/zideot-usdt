import urllib.parse
import re

with open('bot.py', 'r', encoding='utf-8') as f:
    content = f.read()

# الرسالة الجديدة (احترافية، مشوقة، والرابط في الآخر)
magic_text = """🔥🔥 **اكتشاف جديد في عالم الكريبتو!** 🔥🔥

💰 **هل أنت مستعد لتحويل وقتك إلى أرباح حقيقية؟**
🚀 **Zideot USDT** هي منصتك الأولى لربح عملة **USDT** مجاناً!

❓ **كيف تبدأ؟**
1️⃣ اضغط على الرابط بالأسفل.
2️⃣ شاهد إعلانات قصيرة (ثواني معدودة).
3️⃣ اجمع النقاط وحولها لدولارات حقيقية.

🎁 **نظام المكافآت:**
⚡️ كل 10 إعلانات = **1 USDT** (بدون رأس مال!)
👥 كل 10 إحالات = **1 USDT** (أرباح من دعوة أصدقائك)
💳 **الحد الأدنى للسحب:** 10 USDT فقط!

⏳ **لا تفوت الفرصة!** الأماكن محدودة والمكافآت تنفد بسرعة.

👇 **اضغط هنا وابدأ الربح الآن:**"""

# تشفير النص عشان يشتغل صح في رابط المشاركة
encoded_magic = urllib.parse.quote(magic_text)

# استبدال النص القديم
content = re.sub(r'share_text = ".*?"', f'share_text = "{encoded_magic}"', content)

# التأكد من إن الرابط بيجي في الآخر (تيليجرام بيحط الرابط في الآخر أوتوماتيك لو النص مش فيه رابط)
# بس عشان نضمن، هنشيل أي رابط قديم من النص
content = content.replace('https://t.me/', '')

with open('bot.py', 'w', encoding='utf-8') as f:
    f.write(content)
print("✅ تم تحديث رسالة الدعوة بنجاح!")
